def arc_difference(a: float, b: float) -> float:
    """Shortest angular separation, in arcseconds."""
    return abs((a - b + 180.0) % 360.0 - 180.0) * 3600.0


class VsopProvenanceTest(unittest.TestCase):
    """The coefficients must be traceable, and known to be correctly parsed."""

    def test_provenance_is_recorded(self):
        provenance = eph.VSOP87_PROVENANCE
        for key in ("theory", "source", "variant", "validated_against",
                    "files", "truncation_au", "term_counts"):
            with self.subTest(key=key):
                self.assertIn(key, provenance)
        self.assertIn("Bretagnon", provenance["theory"])
        self.assertIn("1988", provenance["theory"])
        self.assertIn("vsop87.chk", provenance["validated_against"])

    def test_source_files_carry_checksums(self):
        for body, entry in eph.VSOP87_PROVENANCE["files"].items():
            with self.subTest(body=body):
                self.assertIn("file", entry)
                self.assertEqual(len(entry["sha256"]), 64)

    def test_vsop_is_used_for_earth_jupiter_and_saturn(self):
        self.assertEqual(eph.VSOP87_BODIES,
                         {"Earth", "Mars", "Jupiter", "Saturn"})
        self.assertEqual(eph.theory_used("Guru"), "VSOP87A")
        self.assertEqual(eph.theory_used("Shani"), "VSOP87A")
        self.assertEqual(eph.theory_used("Earth"), "VSOP87A")

    def test_earth_is_included_deliberately(self):
        """
        Earth is on VSOP not because it is a graha but because every
        geocentric direction is measured from it. Removing it would degrade
        every planet, which is why it is asserted here.
        """
        self.assertIn("Earth", eph.VSOP87_BODIES)
        self.assertEqual(eph.THEORY_FOR_BODY["Earth"], "VSOP87A")

    def test_remaining_bodies_still_use_keplerian_elements(self):
        for body in ("Budha", "Shukra"):
            with self.subTest(body=body):
                self.assertIn("Keplerian", eph.theory_used(body))

    def test_keplerian_path_is_still_available_for_comparison(self):
        """The old theory is retained so the two can be compared directly."""
        xyz = eph.keplerian_xyz("Jupiter", 2451545.0)
        self.assertEqual(len(xyz), 3)
        vsop = eph.vsop87_xyz("Jupiter", 2451545.0)
        # They agree to roughly the Keplerian element set's own accuracy.
        self.assertLess(abs(xyz[0] - vsop[0]), 0.05)


class MeasuredAccuracyTest(unittest.TestCase):
    """
    EXTERNALLY BENCHMARKED figures, pinned so a regression is loud.

    Tolerances sit just above the measured values. They exist to catch a
    change, not to assert an accuracy the engine has not demonstrated.
    """

    # body -> (max arcsec allowed, description)
    LIMITS = {
        "Surya": 40.0,
        "Chandra": 15.0,
        "Budha": 20.0,
        "Shukra": 45.0,
        "Mangal": 15.0,
        "Guru": 8.0,
        "Shani": 10.0,
    }

    @classmethod
    def setUpClass(cls):
        if not os.path.exists(FIXTURE):
            raise unittest.SkipTest(
                "planetary_accuracy.json missing — run "
                ".venv/bin/python tools/generate_accuracy_fixture.py")
        with open(FIXTURE, encoding="utf-8") as handle:
            cls.data = json.load(handle)

    def test_fixture_covers_the_required_years(self):
        """Part 1 names the years that must be present."""
        years = {int(case["utc"][:4]) for case in self.data["cases"]}
        for required in (1800, 1850, 1900, 1950, 2000, 2026, 2050):
            with self.subTest(year=required):
                self.assertIn(required, years)

    def test_fixture_covers_the_required_configurations(self):
        kinds = {case["kind"] for case in self.data["cases"]}
        for required in ("anchor_year", "direct", "retrograde", "station",
                         "opposition", "conjunction", "sign_boundary",
                         "deterministic_random"):
            with self.subTest(kind=required):
                self.assertIn(required, kinds)

    def test_jupiter_and_saturn_within_measured_limits(self):
        for case in self.data["cases"]:
            jd_tt = eph.jd_ut_to_tt(case["jd_ut"])
            for body in ("Guru", "Shani"):
                expected = case["bodies"][body]["tropical"]
                error = arc_difference(
                    eph.tropical_longitude(body, jd_tt), expected)
                with self.subTest(case=case["label"], body=body):
                    self.assertLess(
                        error, self.LIMITS[body],
                        f"{body} error {error:.2f}\" at {case['label']}")

    def test_every_body_within_measured_limits(self):
        for case in self.data["cases"]:
            jd_tt = eph.jd_ut_to_tt(case["jd_ut"])
            for body, limit in self.LIMITS.items():
                expected = case["bodies"][body]["tropical"]
                error = arc_difference(
                    eph.tropical_longitude(body, jd_tt), expected)
                with self.subTest(case=case["label"], body=body):
                    self.assertLess(error, limit)

    def test_statistics_are_recorded_for_jupiter_and_saturn(self):
        """Part 1 requires max, mean, median and p95 for each, separately."""
        stats = self.data["statistics"]
        for body in ("Guru", "Shani"):
            with self.subTest(body=body):
                self.assertIn(body, stats)
                for key in ("max_arcsec", "mean_arcsec", "median_arcsec",
                            "p95_arcsec"):
                    self.assertIn(key, stats[body])

    def test_recorded_improvement_over_the_keplerian_elements(self):
        """The upgrade must be demonstrated, not asserted."""
        stats = self.data["statistics"]
        for body in ("Guru", "Shani"):
            with self.subTest(body=body):
                before = stats[body]["keplerian_max_arcsec"]
                after = stats[body]["max_arcsec"]
                # 300" rather than the ~600" of the dense 1800-2050 sweep:
                # these 51 cases are chosen for configuration coverage, not to
                # hunt the worst case, so they sample a smaller maximum.
                self.assertGreater(before, 300.0,
                                   "the old theory should be the bad one")
                self.assertLess(after, 10.0)
                self.assertGreater(before / after, 50.0)

    def test_retrograde_and_station_flags_agree_with_the_reference(self):
        for case in self.data["cases"]:
            jd_tt = eph.jd_ut_to_tt(case["jd_ut"])
            for body in ("Guru", "Shani", "Mangal"):
                expected = case["bodies"][body]
                got = eph.daily_motion(body, jd_tt)
                if abs(expected["speed"]) < 0.002:
                    continue        # too near a station to demand a direction
                with self.subTest(case=case["label"], body=body):
                    self.assertEqual(got < 0, expected["retrograde"],
                                     f"{body} direction at {case['label']}")

    def test_sign_classification_matches_the_reference(self):
        for case in self.data["cases"]:
            chart = JyotishChart(jde=case["jd_ut"], lat=0.0, lon=0.0)
            for body in ("Guru", "Shani"):
                expected = case["bodies"][body]
                with self.subTest(case=case["label"], body=body):
                    self.assertEqual(chart.planets[body].rashi,
                                     expected["sign"])
                    self.assertEqual(chart.planets[body].nakshatra,
                                     expected["nakshatra"])
                    self.assertEqual(chart.planets[body].pada,
                                     expected["pada"])


class UncertaintyConstantsTest(unittest.TestCase):
    """The envelopes must stay tied to the measurements they came from."""

    @classmethod
    def setUpClass(cls):
        with open(PROFILE, encoding="utf-8") as handle:
            cls.profile = json.load(handle)

    def test_envelopes_match_the_measured_profile(self):
        """
        A stale tolerance is worse than none: it silently claims certainty the
        engine no longer has. This ties the constants to the measurement.
        """
        measured = self.profile["tropical_longitude"]
        for body, envelope in ACCURACY_ARCMIN.items():
            key = "Rahu_true" if body in ("Rahu", "Ketu") else body
            with self.subTest(body=body):
                self.assertIn(key, measured)
                self.assertAlmostEqual(
                    envelope, measured[key]["max_arcmin"], delta=0.02,
                    msg=f"{body}: constant {envelope}' vs measured "
                        f"{measured[key]['max_arcmin']}'")

    def test_the_limiting_body_is_the_true_node(self):
        """
        V1.3 moved Mars to VSOP87A, so the worst envelope is now the true
        node at 1.11'. That is not a planetary-theory problem: the node is
        derived from this engine's own lunar series, so improving it means
        improving that series. Scope was not widened to chase it.
        """
        worst = max(ACCURACY_ARCMIN, key=ACCURACY_ARCMIN.get)
        self.assertIn(worst, ("Rahu", "Ketu"))
        self.assertLess(ACCURACY_ARCMIN["Mangal"], 0.2,
                        "Mars should no longer be a large envelope")

    def test_vsop_bodies_have_the_smallest_envelopes(self):
        """All four VSOP87 bodies sit far below the Keplerian ones."""
        vsop = ("Guru", "Shani", "Mangal")
        keplerian = ("Budha", "Shukra")
        for body in vsop:
            with self.subTest(body=body):
                self.assertLess(ACCURACY_ARCMIN[body], 0.2)
        self.assertLess(max(ACCURACY_ARCMIN[b] for b in vsop),
                        max(ACCURACY_ARCMIN[b] for b in keplerian))

    def test_envelope_lookup(self):
        self.assertEqual(envelope_for("Guru"), ACCURACY_ARCMIN["Guru"])
        self.assertEqual(envelope_for("Lagna"), LAGNA_ARCMIN)
        self.assertLess(envelope_for("Rahu", true_node=False),
                        envelope_for("Rahu", true_node=True))

    def test_unknown_body_falls_back_to_the_worst_envelope(self):
        self.assertEqual(envelope_for("Unknown"), max(ACCURACY_ARCMIN.values()))


class BoundaryDetectionTest(unittest.TestCase):
    """Part 2: uncertainty must be exposed, never silently swallowed."""

    def spans(self):
        from engine.vargas import VARGA_ORDER, VARGA_SPECS
        return varga_division_spans(
            {key: VARGA_SPECS[key].divisions for key in VARGA_ORDER})

    # Rahu has the widest envelope (1.11') since Mars moved to VSOP87A in
    # V1.3, and Guru the narrowest (0.05'). The pair gives a 22x ratio, which
    # is what makes the per-body behaviour visible.
    WIDE = "Rahu"
    NARROW = "Guru"

    def test_warns_when_nearer_the_boundary_than_the_envelope(self):
        result = assess_position(self.WIDE, 90.0 - 0.5 / 60.0)
        self.assertTrue(result.boundary_warning)
        self.assertEqual(result.boundary_type, "rashi")

    def test_does_not_warn_when_comfortably_inside(self):
        result = assess_position(self.WIDE, 105.0)
        self.assertFalse(result.boundary_warning)
        self.assertIsNone(result.boundary_type)

    def test_accuracy_decides_the_verdict_not_the_distance_alone(self):
        """
        The same longitude is unresolved for Mars and resolved for Jupiter,
        because their envelopes differ by sixty-fold. This is the whole point
        of the feature.
        """
        longitude = 90.0 - 0.5 / 60.0
        self.assertTrue(assess_position(self.WIDE, longitude).boundary_warning)
        self.assertFalse(assess_position(self.NARROW, longitude).boundary_warning)

    def test_warns_on_both_sides_of_a_boundary(self):
        for offset in (-0.3 / 60.0, +0.3 / 60.0):
            with self.subTest(offset=offset):
                self.assertTrue(
                    assess_position(self.WIDE, 90.0 + offset).boundary_warning)

    def test_detects_each_boundary_kind(self):
        kinds = set()
        for longitude in (30.0, float(NAKSHATRA_SPAN), float(PADA_SPAN)):
            result = assess_position(self.WIDE, longitude - 0.2 / 60.0)
            kinds.update(result.boundary_types)
        for kind in ("rashi", "nakshatra", "pada"):
            with self.subTest(kind=kind):
                self.assertIn(kind, kinds)

    def test_varga_boundaries_are_reported(self):
        result = assess_position(self.WIDE, 90.0 - 0.5 / 60.0,
                                 varga_spans=self.spans())
        varga_warnings = [k for k in result.boundary_types if k.startswith("D")]
        self.assertTrue(varga_warnings)

    def test_d30_is_excluded_from_varga_spans(self):
        """
        Trimshamsha has unequal parts, so one span cannot describe it.
        Reporting nothing beats reporting a number that is not true.
        """
        self.assertNotIn("D30", self.spans())

    def test_finest_boundary_is_reported_first(self):
        result = assess_position(self.WIDE, 90.0 - 0.3 / 60.0)
        self.assertEqual(result.boundary_type, "rashi")

    def test_serialised_shape_matches_the_brief(self):
        result = assess_position("Shani", 89.998, theory="VSOP87A")
        data = result.to_dict()
        for key in ("planet", "longitude", "accuracy_arcmin",
                    "boundary_warning", "boundary_type"):
            with self.subTest(key=key):
                self.assertIn(key, data)
        self.assertEqual(data["planet"], "Shani")
        self.assertIsInstance(data["boundary_warning"], bool)

    def test_distance_is_measured_to_the_nearer_edge(self):
        below = assess_position("Guru", 29.99)
        above = assess_position("Guru", 30.01)
        rashi_below = [p for p in below.proximities
                       if p.boundary_type == "rashi"][0]
        rashi_above = [p for p in above.proximities
                       if p.boundary_type == "rashi"][0]
        self.assertEqual(rashi_below.direction, "above")
        self.assertEqual(rashi_above.direction, "below")
        self.assertAlmostEqual(rashi_below.distance_arcmin, 0.6, places=4)
        self.assertAlmostEqual(rashi_above.distance_arcmin, 0.6, places=4)

    def test_summary_lists_affected_bodies(self):
        uncertainties = {
            "Rahu": assess_position("Rahu", 90.0 - 0.5 / 60.0),
            "Guru": assess_position("Guru", 105.0),
        }
        summary = summarise(uncertainties)
        self.assertEqual(summary["bodies_with_warnings"], ["Rahu"])
        self.assertEqual(summary["safety_factor"], SAFETY_FACTOR)
        self.assertIn("Rahu", summary["warnings"])


class ChartUncertaintyIntegrationTest(unittest.TestCase):
    """The verdict must reach the feature layer, not stay in the module."""

    def test_features_carry_uncertainty_for_every_graha(self):
        import datetime
        from engine.features import build_chart_features
        from engine.planets import jde_from_datetime
        chart = JyotishChart(
            jde=jde_from_datetime(datetime.datetime(1988, 8, 30, 14, 48)),
            lat=26.9124, lon=75.7873)
        features = build_chart_features(chart)
        for name, graha in features.planets.items():
            with self.subTest(graha=name):
                self.assertIsNotNone(graha.uncertainty)
                self.assertTrue(graha.theory)
                self.assertIsInstance(graha.boundary_warning, bool)
        self.assertIsNotNone(features.lagna_uncertainty)
        self.assertIn("bodies_with_warnings", features.uncertainty)

    def test_a_chart_with_a_body_on_a_boundary_is_flagged(self):
        from engine.features import build_chart_features
        chart = JyotishChart.from_sidereal_longitudes(
            lagna_lon=15.0,
            planet_lons={"Surya": 100.0, "Chandra": 200.0,
                         "Rahu": 90.0 - 0.5 / 60.0})
        features = build_chart_features(chart)
        self.assertIn("Rahu", features.uncertainty["bodies_with_warnings"])
        self.assertTrue(features.planets["Rahu"].boundary_warning)
        self.assertTrue(any("not resolved" in w for w in features.warnings))


