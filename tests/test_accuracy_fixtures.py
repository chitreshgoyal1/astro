"""
Planetary accuracy fixtures (V1.2 Parts 1-2)
---------------------------------------------
Pins the measured accuracy of the ephemeris, and the uncertainty machinery
built on top of it.

WHAT THESE TESTS ARE AND ARE NOT
    The fixture in tests/fixtures/planetary_accuracy.json was generated by
    tools/generate_accuracy_fixture.py from the Swiss Ephemeris — an
    independent theory from the ones this engine implements (VSOP87 for
    Earth/Jupiter/Saturn, JPL Keplerian elements for the rest, Meeus for the
    luminaries). Comparing against it is therefore EXTERNAL BENCHMARKING, not
    self-confirmation.

    What it cannot tell us is whether the Swiss Ephemeris is right. For the
    outer planets over this span, Moshier itself differs from the JPL DE
    series by of order an arcsecond, so a measured residual of 3-4" for
    Jupiter and Saturn is at the level of the reference's own uncertainty and
    should not be read as this engine being accurate to 3". It is accurate to
    "no worse than a few arcseconds, as far as this reference can resolve".

    The VSOP87 coefficients themselves were validated separately and more
    strongly: against vsop87.chk, the reference values published by the
    theory's own authors. See tools/build_vsop87.py --validate.
"""

