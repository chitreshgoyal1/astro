"""
Source validation report (V1.3 Part 18)
----------------------------------------
Generates SOURCE_VALIDATION.md from the registry, so the document cannot
drift away from what the code actually asserts.

The report leads with what is NOT established. A provenance report that opens
with its successes and buries the unverified count is doing the opposite of
its job.
"""

from __future__ import annotations

import os
from collections import Counter

from ..rules import RULE_PROFILES, all_rules, rules_for_profile
from ..vargas import VARGA_ORDER, VARGA_SPECS
from .editions import ALL_WITNESSES, UNAVAILABLE_WORKS
from .models import (
    CLASSIFICATION_MEANING, STATUS_MEANING, RuleClassification,
    ValidationStatus,
)
from ..gochara.rules import UNIMPLEMENTED_LAYERS
from .review import REVIEW_TASKS
from .registry import (
    CONFLICTS, REGISTRY_VERSION, REVIEW_QUEUE, REVIEWED_ON,
    all_recorded_evidence, evidence_for, registry_summary, witnesses_for,
)
from .validation import (
    STRICT_PROFILE_MINIMUM, STRICT_PROFILE_REQUIREMENTS,
    strict_profile_eligible,
)

_STATUS_MARK = {
    ValidationStatus.UNVERIFIED: "—",
    ValidationStatus.TEXT_LOCATED: "·",
    ValidationStatus.WITNESS_RECORDED: "◦",
    ValidationStatus.TRANSLATION_CHECKED: "◦",
    ValidationStatus.RULE_INTERPRETATION_MAPPED: "◐",
    ValidationStatus.IMPLEMENTATION_MATCHED: "●",
    ValidationStatus.SECOND_WITNESS_CHECKED: "●",
    ValidationStatus.VALIDATED_FOR_PROFILE: "◆",
    ValidationStatus.TRADITION_VALIDATED: "★",
    ValidationStatus.CONFLICTING_SOURCES: "⚠",
    ValidationStatus.IMPLEMENTATION_DIVERGES: "✗",
}


def _witness_cell(subject: str) -> str:
    witnesses = witnesses_for(subject)
    if not witnesses:
        return "*none*"
    return "<br>".join(f"`{w.id}`" for w in witnesses)


def _rule_rows() -> list[str]:
    rows = []
    for rule in sorted(all_rules(), key=lambda r: r.id):
        evidence = evidence_for(rule.id)
        eligible, _ = strict_profile_eligible(evidence, witnesses_for(rule.id))
        rows.append(
            f"| `{rule.id}` | {rule.category} | {_witness_cell(rule.id)} | "
            f"{_STATUS_MARK[evidence.validation_status]} "
            f"{evidence.validation_status.value} | "
            f"{evidence.classification.value} | "
            f"{'yes' if evidence.conflicts else '—'} | "
            f"{'YES' if eligible else 'no'} |")
    return rows


def _varga_rows() -> list[str]:
    rows = []
    for chart in VARGA_ORDER:
        for convention in VARGA_SPECS[chart].conventions:
            subject = f"{chart}/{convention}"
            evidence = evidence_for(subject, kind="varga")
            from ..varga_metadata import metadata_for
            meta = metadata_for(chart, convention)
            alias = " *(alias)*" if meta.is_deprecated_alias else ""
            rows.append(
                f"| {chart} | `{convention}`{alias} | "
                f"{_witness_cell(subject)} | "
                f"{_STATUS_MARK[evidence.validation_status]} "
                f"{evidence.validation_status.value} | "
                f"{', '.join(evidence.ambiguities) or '—'} |")
    return rows


def build_report() -> str:
    summary = registry_summary()
    rules = all_rules()
    statuses = Counter(evidence_for(r.id).validation_status for r in rules)
    classes = Counter(evidence_for(r.id).classification for r in rules)

    unverified = statuses[ValidationStatus.UNVERIFIED]
    located = len(rules) - unverified

    lines: list[str] = []
    add = lines.append

    add("# Source Validation Report")
    add("")
    add(f"**Registry version:** {REGISTRY_VERSION}  ")
    add(f"**Reviewed:** {REVIEWED_ON}  ")
    add("**Generated by:** `engine/sources/report.py` — regenerate with "
        "`python3 -m tools.generate_source_report`")
    add("")
    add("---")
    add("")

    # ── the honest headline ─────────────────────────────────────────────────
    add("## 1. What this report establishes, and what it does not")
    add("")
    add("Four claims are kept separate throughout. **None is evidence for "
        "any other.**")
    add("")
    add("| Claim | Status in this build |")
    add("|---|---|")
    add("| **COMPUTATIONALLY TESTED** | Yes, extensively. The test suite "
        "establishes that the code does what it was told to. |")
    add("| **EXTERNALLY BENCHMARKED** | Yes, for astronomy. Positions agree "
        "with an independent reference ephemeris. |")
    add(f"| **TEXTUAL SOURCE LOCATED** | For **{located} of {len(rules)}** "
        "yoga rules. |")
    add("| **TRADITION/SOURCE VALIDATED** | **Nothing.** Not one rule and "
        "not one Varga convention. |")
    add("")
    add("### The headline number")
    add("")
    add(f"**{unverified} of {len(rules)} shipped yoga rules "
        f"({100 * unverified / len(rules):.0f}%) have no examined textual "
        f"witness at all.**")
    add("")
    add("Those rules carry citation strings like `BPHS ch.36`. Those strings "
        "were written from memory by the implementing model during V1.1 and "
        "V1.2. None has ever been checked against an edition, several are "
        "probably wrong, and a bare work name does not identify a passage in "
        "any case — see §6.")
    add("")
    add("They are **not deleted**. A rule being untraced is not the same as "
        "a rule being wrong, and most of these are in common traditional "
        "use. They are classified, excluded from the evidence-gated profile, "
        "and reported here.")
    add("")

    # ── witnesses ───────────────────────────────────────────────────────────
    add("---")
    add("")
    add("## 2. Witnesses actually obtained")
    add("")
    add(f"**{summary['witnesses_registered']} witnesses, all from one work.**")
    add("")
    add("| ID | Work | Authority | Locator | Edition |")
    add("|---|---|---|---|---|")
    for witness in ALL_WITNESSES:
        add(f"| `{witness.id}` | {witness.work} | {witness.authority.value} | "
            f"{witness.locator or '—'} | {witness.edition or '—'} |")
    add("")
    add("The digital text carries a recorded SHA-256 and a retrieval URL, so "
        "the exact bytes examined can be re-obtained and re-checked.")
    add("")

    add("### Works cited by the engine for which NO witness exists")
    add("")
    add("| Work | Cited by rules? | Why unavailable |")
    add("|---|---|---|")
    for key, entry in UNAVAILABLE_WORKS.items():
        add(f"| {entry['work']} | "
            f"{'yes' if entry['cited_by_rules'] else 'notes only'} | "
            f"{entry['why_unavailable']} |")
    add("")
    add("**Brihat Parashara Hora Shastra is the significant absence.** It is "
        "cited by roughly a hundred rules and no witness for it could be "
        "obtained here.")
    add("")

    # ── yoga table ──────────────────────────────────────────────────────────
    add("---")
    add("")
    add("## 3. Rules")
    add("")
    add("| Rule | Category | Witness | Status | Classification | Conflict? | "
        "Strict-eligible? |")
    add("|---|---|---|---|---|---|---|")
    lines.extend(_rule_rows())
    add("")
    add("### Totals")
    add("")
    add("| Measure | Count |")
    add("|---|---|")
    add(f"| Rules total | {len(rules)} |")
    add(f"| Source located (any status above UNVERIFIED) | {located} |")
    add(f"| Implementation matched | "
        f"{statuses[ValidationStatus.IMPLEMENTATION_MATCHED]} |")
    add(f"| Conflicting sources | "
        f"{statuses[ValidationStatus.CONFLICTING_SOURCES]} |")
    add(f"| **Tradition validated** | "
        f"**{statuses[ValidationStatus.TRADITION_VALIDATED]}** |")
    add(f"| **Unverified** | **{unverified}** |")
    add("")
    add("By classification:")
    add("")
    add("| Classification | Count | Meaning |")
    add("|---|---|---|")
    for classification in RuleClassification:
        add(f"| {classification.value} | {classes[classification]} | "
            f"{CLASSIFICATION_MEANING[classification]} |")
    add("")

    # ── calculation modules (V1.4) ──────────────────────────────────────────
    calculations = [e for e in all_recorded_evidence()
                    if e.kind == "calculation"]
    if calculations:
        add("---")
        add("")
        add("## 3A. Calculation modules (V1.4)")
        add("")
        add("Shadbala, Ashtakavarga and the house systems, added in V1.4. "
            "These were implemented AFTER a witness was obtained rather than "
            "from memory, which is the discipline the V1 yoga catalog lacked.")
        add("")
        add("| Module | Witness | Status | Classification | Review needed? |")
        add("|---|---|---|---|---|")
        for evidence in sorted(calculations, key=lambda e: e.subject):
            add(f"| `{evidence.subject}` | "
                f"{_witness_cell(evidence.subject)} | "
                f"{_STATUS_MARK[evidence.validation_status]} "
                f"{evidence.validation_status.value} | "
                f"{evidence.classification.value} | "
                f"{'yes' if evidence.needs_human_review else 'no'} |")
        add("")
        located = sum(1 for e in calculations
                      if e.validation_status is not ValidationStatus.UNVERIFIED)
        add(f"**{located} of {len(calculations)}** calculation modules have a "
            f"located witness — against **5 of 110** for the yoga catalog. "
            f"Sourcing first and implementing second produces a very "
            f"different ratio.")
        add("")

    # ── gochara (V1.8) ──────────────────────────────────────────────────────
    add("---")
    add("")
    add("## 3B. Gochara — transit rules (V1.8)")
    add("")
    add("Four releases in the making, and the outcome is asymmetric in a "
        "way worth stating plainly: the LARGER of the two located "
        "passages is fully implemented and still cannot carry a "
        "conclusion.")
    add("")
    add("| Rule | Frame | Witnesses | Status | Strict-eligible |")
    add("|---|---|---|---|---|")
    for rule_id, frame, note in (
            ("gochara/vedha_from_moon", "Chandra",
             "no — names no bhāva"),
            ("gochara/dasha_lord_from_lagna", "Lagna", "**yes**")):
        evidence = evidence_for(rule_id, kind="calculation")
        add(f"| `{rule_id}` | {frame} | "
            f"{len(evidence.witness_ids)} | "
            f"{_STATUS_MARK[evidence.validation_status]} "
            f"{evidence.validation_status.value} | {note} |")
    add("")
    add("Phaladīpikā 26 gives each graha's favourable houses from the "
        "Moon and makes every one conditional on vedha. All 36 pairs are "
        "implemented, with both reciprocal exemptions — the Sun suffers "
        "no vedha from Saturn, the Moon none from Mercury.")
    add("")
    add("It reaches no life area because it judges a transit in the "
        "Chandra's frame without naming a bhāva, and this engine's bhāva "
        "significations are stated from the Lagna. There is no sourced "
        "path from one to the other, so chapter 26 narrows what the "
        "engine claims rather than widening it.")
    add("")
    add("Rāhu and Ketu take the Sun's favourable houses (26.2, "
        "`tigmāṃśuvad bhoginau`) and get **no vedha table**. Copying the "
        "Sun's row across would be a one-line change and an invention: "
        "26.2 transfers the RESULTS, and whether it transfers the "
        "obstructions is exactly what the text leaves open.")
    add("")
    add("### Located and deliberately not implemented")
    add("")
    add("| Passage | Subject | Why not |")
    add("|---|---|---|")
    for item in UNIMPLEMENTED_LAYERS:
        add(f"| {item['locator']} | {item['subject']} | "
            f"{item['why_not'].split('.')[0]}. |")
    add("")

    # ── the review pipeline (V1.8) ──────────────────────────────────────────
    add("---")
    add("")
    add("## 3C. Works held and not read (V1.8)")
    add("")
    add("Availability and readership are separate axes. A work can be "
        "held in full and completely unread, which is Sārāvalī's "
        "position and is NOT the same as being unavailable — a "
        "distinction this report got wrong for four releases.")
    add("")
    add("| Work | Availability | Review stage | Blocked on |")
    add("|---|---|---|---|")
    for task in REVIEW_TASKS:
        add(f"| {task.work} | {task.availability.value} | "
            f"{task.stage.value} | "
            f"{(task.blocked_on or '—').split('.')[0]}. |")
    add("")
    add("**OCR is never evidence.** It may be used to find where to "
        "look; a passage located that way must be read on the page image "
        "before a witness is registered from it. The reason is concrete: "
        "the V1.8 gochara audit found a volunteer transliteration — far "
        "cleaner input than OCR — corrupt in two places, one of which "
        "would have produced a wrong vedha table.")
    add("")

    # ── varga table ─────────────────────────────────────────────────────────
    add("---")
    add("")
    add("## 4. Varga conventions")
    add("")
    add("| Chart | Convention | Witness | Status | Known ambiguities |")
    add("|---|---|---|---|---|")
    lines.extend(_varga_rows())
    add("")
    add("`(alias)` marks a convention that is mathematically identical to its "
        "chart's default at every longitude — see §7.")
    add("")

    # ── conflicts ───────────────────────────────────────────────────────────
    add("---")
    add("")
    add("## 5. Source conflicts")
    add("")
    add(f"**{len(CONFLICTS)} registered.** Conflicts are modelled, not "
        "resolved: where both readings are live traditions the answer is two "
        "profiles, never one blended definition that neither authority would "
        "recognise.")
    add("")
    for conflict in CONFLICTS:
        add(f"### `{conflict.id}`")
        add("")
        add(f"**Topic:** {conflict.topic}  ")
        add(f"**Witness A:** {conflict.witness_a}  ")
        add(f"**Witness B:** {conflict.witness_b}  ")
        add(f"**Status:** {conflict.resolution_status}")
        add("")
        add(conflict.difference)
        add("")
        if conflict.resolution_note:
            add(f"*Resolution:* {conflict.resolution_note}")
            add("")

    # ── editions ────────────────────────────────────────────────────────────
    add("---")
    add("")
    add("## 6. Why a bare work name is not a citation")
    add("")
    add("BPHS is a textual tradition, not one immutable document. Editions "
        "differ in chapter division, verse numbering, Sanskrit readings and "
        "translation. `BPHS ch.36` identifies a passage about as precisely "
        "as `chapter 36` identifies a passage of the Bible.")
    add("")
    add("Every witness in this registry therefore records its edition, its "
        "locator, and where it was retrieved from. A citation that cannot "
        "name its witness is recorded as UNVERIFIED regardless of how "
        "confident it sounds.")
    add("")
    add("A Sanskrit text and a translation of it are **two witnesses**, never "
        "one. A translator's choice among readings of an ambiguous compound "
        "is an interpretation, and recording it under the original's name "
        "hides that.")
    add("")

    # ── aliases ─────────────────────────────────────────────────────────────
    add("---")
    add("")
    add("## 7. Configuration aliases")
    add("")
    add("Four Varga conventions execute mathematics identical to their "
        "chart's default at every longitude. They are retained for "
        "compatibility and marked `is_deprecated_alias`, so that no user is "
        "offered a choice that cannot change anything:")
    add("")
    add("| Chart | Alias | Identical to | Why |")
    add("|---|---|---|---|")
    from ..varga_metadata import all_metadata
    for meta in all_metadata():
        if not meta.get("is_deprecated_alias"):
            continue
        add(f"| {meta['chart']} | `{meta['convention_id']}` | "
            f"`{meta.get('identical_to', '?')}` | "
            f"{meta.get('notes', '')} |")
    add("")

    # ── strict profile ──────────────────────────────────────────────────────
    add("---")
    add("")
    add("## 8. The evidence-gated profile")
    add("")
    strict = rules_for_profile("parashari_strict")
    add(f"`parashari_strict` admits **{len(strict)} of {len(rules)} rules**.")
    add("")
    add(f"Minimum status: **{STRICT_PROFILE_MINIMUM.value}**, plus:")
    add("")
    for requirement in STRICT_PROFILE_REQUIREMENTS:
        add(f"- {requirement}")
    add("")
    add("Membership is computed from the registry, not from a hand-kept "
        "list, so a rule cannot be admitted by editing the catalog — only by "
        "producing evidence. A test fails if an unqualified rule appears.")
    add("")
    if strict:
        add("Admitted:")
        add("")
        for rule in strict:
            add(f"- `{rule.id}` — {rule.name}")
    else:
        add("Nothing currently qualifies.")
    add("")
    add("> This profile is deliberately tiny. That is the finding of this "
        "audit, not a defect in it.")
    add("")

    # ── review queue ────────────────────────────────────────────────────────
    add("---")
    add("")
    add("## 9. Open questions for human review")
    add("")
    add(f"**{len(REVIEW_QUEUE)} items.** These cannot safely be settled by "
        "the implementing model. A model that resolves a Sanskrit ambiguity "
        "by choosing the reading which makes its own code correct has "
        "validated nothing — it has laundered a guess.")
    add("")
    for item in REVIEW_QUEUE:
        add(f"### {item.subject}")
        add("")
        add(f"**Reason:** `{item.reason.value}`  ")
        add(f"**Blocking:** {'yes' if item.blocking else 'no'}")
        add("")
        add(f"**Question.** {item.question}")
        add("")
        add(f"**Current behaviour.** {item.current_behaviour}")
        add("")

    # ── statuses ────────────────────────────────────────────────────────────
    add("---")
    add("")
    add("## 10. Validation lifecycle")
    add("")
    add("| Status | Meaning |")
    add("|---|---|")
    for status in ValidationStatus:
        add(f"| `{status.value}` | {STATUS_MEANING[status]} |")
    add("")
    add("Each status has a stated evidence requirement enforced in "
        "`engine/sources/validation.py`. A status is a claim the code checks, "
        "not a label somebody typed.")
    add("")
    add("---")
    add("")
    add("## 11. What would move these numbers")
    add("")
    add("1. **A named BPHS edition.** Would put roughly a hundred rules in "
        "reach of TEXT_LOCATED. The edition must be identified; the chapter "
        "numbering is not stable.")
    add("2. **Sārāvalī and Phaladīpikā.** Between them they are the usual "
        "attribution for the Pañca Mahāpuruṣa and the Sun yogas, neither of "
        "which is in Bṛhajjātaka.")
    add("3. **A Sanskritist**, for the nine items in §9 that turn on reading "
        "the text rather than finding it.")
    add("4. **A second independent witness** for the five passages already "
        "located — the remaining step before anything could be "
        "TRADITION_VALIDATED.")
    add("")
    return "\n".join(lines)


def write_report(path: str) -> str:
    content = build_report()
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(content)
        handle.write("\n")
    return path
