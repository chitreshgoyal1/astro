def delta_t_seconds(jd_ut: float) -> float:
    """
    ΔT = TT − UT in seconds.

    Within 1800–2026 this interpolates observed values and is accurate to a
    fraction of a second. Outside that span it is a projection: the Earth's
    rotation cannot be predicted, so values for future dates carry a growing
    uncertainty of several seconds.
    """
    y = jd_to_year(jd_ut)

    if _DELTA_T_TABLE_START <= y <= _DELTA_T_TABLE_END:
        position = (y - _DELTA_T_TABLE_START) / _DELTA_T_TABLE_STEP
        index = min(int(position), len(_DELTA_T_TABLE) - 2)
        fraction = position - index
        low, high = _DELTA_T_TABLE[index], _DELTA_T_TABLE[index + 1]
        return low + (high - low) * fraction

    if y > _DELTA_T_TABLE_END:
        t = y - 2000
        projected = 62.92 + 0.32217 * t + 0.005589 * t * t
        return projected + _DELTA_T_PROJECTION_OFFSET

    # Before the table: Espenak & Meeus polynomials.
    if y < 1700:
        u = (y - 1820) / 100.0
        return -20 + 32 * u * u
    t = y - 1700
    return (8.83 + 0.1603 * t - 0.0059285 * t**2
            + 0.00013336 * t**3 - t**4 / 1174000.0)


def jd_ut_to_tt(jd_ut: float) -> float:
    """Terrestrial Time JD, which is what the position series expect."""
    return jd_ut + delta_t_seconds(jd_ut) / 86400.0


