def julian_day(year: int, month: int, day: int, hour: float = 0.0) -> float:
    """Julian Day from a calendar date (Gregorian after 1582-10-15)."""
    if month <= 2:
        year -= 1
        month += 12
    a = year // 100
    b = 2 - a + a // 4
    return (int(365.25 * (year + 4716)) + int(30.6001 * (month + 1))
            + day + hour / 24.0 + b - 1524.5)


