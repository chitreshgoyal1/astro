def _solve_kepler(mean_anomaly_deg: float, e: float) -> float:
    """Eccentric anomaly in degrees, by Newton iteration."""
    m = math.radians((mean_anomaly_deg + 180.0) % 360.0 - 180.0)
    ecc_anom = m + e * math.sin(m)
    for _ in range(12):
        delta = (ecc_anom - e * math.sin(ecc_anom) - m) / (1 - e * math.cos(ecc_anom))
        ecc_anom -= delta
        if abs(delta) < 1e-12:
            break
    return math.degrees(ecc_anom)


def _mean_anomaly(name: str, t: float) -> float:
    """Mean anomaly of a planet at time t (Julian centuries from J2000)."""
    base, rate = _ELEMENTS[name]
    mean_lon = base[3] + rate[3] * t
    peri_lon = base[4] + rate[4] * t
    return _deg(mean_lon - peri_lon)


#: V1.8 Part 13/15. The series evaluation is the engine's hottest function by
#: a wide margin — a one-year transit scan called it 97,000 times and spent
#: two thirds of the scan inside it, most of that in 64 million cosines.
#:
#: It is cached because it is the ideal case for caching and not because it
#: is convenient: a pure function of two immutable arguments, sitting
#: UPSTREAM of every methodology choice. Ayanamsha, node mode, house system
#: and rule profile are all applied later, so there is no profile for a
#: cached value to leak into — the one failure mode Part 15 names. A
#: deep-equality test asserts the cached and uncached paths agree exactly.
#:
#: The wins come from one chart needing Earth's position once per body, and
#: from the bisection re-sampling instants the coarse pass already visited.
_VSOP_CACHE: dict = {}
_VSOP_CACHE_LIMIT = 65536


def clear_vsop_cache() -> None:
    """Drop the series cache. For tests that measure cold cost."""
    _VSOP_CACHE.clear()


def vsop_cache_stats() -> dict:
    return {"entries": len(_VSOP_CACHE), "limit": _VSOP_CACHE_LIMIT}


def vsop87_xyz(name: str, jd_tt: float) -> tuple[float, float, float]:
    """
    Heliocentric rectangular coordinates from the VSOP87A series, in au, on
    the dynamical ecliptic and equinox of J2000 — the same frame the Keplerian
    path produces, so the two are interchangeable upstream of light-time.
    """
    key = (name, jd_tt)
    hit = _VSOP_CACHE.get(key)
    if hit is not None:
        return hit
    result = _vsop87_xyz_uncached(name, jd_tt)
    if len(_VSOP_CACHE) >= _VSOP_CACHE_LIMIT:
        _VSOP_CACHE.clear()
    _VSOP_CACHE[key] = result
    return result


#: The same series, flattened from dict-of-lists to tuple-of-tuples once at
#: import. Iteration order is IDENTICAL — Python dicts preserve insertion
#: order and this is built by walking them — which matters more than the
#: speed: floating-point summation is not associative, so a reordering here
#: would move the last digits of every position in the engine and every
#: benchmarked accuracy figure with them.
_VSOP_FLAT: dict = {
    name: tuple(tuple((power, tuple(terms))
                      for power, terms in series[axis].items())
                for axis in (0, 1, 2))
    for name, series in VSOP87A.items()
}


def _vsop87_xyz_uncached(name: str, jd_tt: float) -> tuple[float, float, float]:
    """
    The series itself.

    Kept as a separate function from the cached entry point so a test can
    exercise both paths and assert they agree exactly, and micro-optimised
    only in ways that cannot move a result: a local binding for math.cos and
    tuple iteration in place of repeated dict lookups. The arithmetic, and
    above all the order of the additions, is untouched.
    """
    t = (jd_tt - 2451545.0) / 365250.0
    cos = math.cos
    out = []
    for blocks in _VSOP_FLAT[name]:
        total = 0.0
        for power, terms in blocks:
            block = 0.0
            for amplitude, phase, frequency in terms:
                block += amplitude * cos(phase + frequency * t)
            total += block * (t ** power)
        out.append(total)
    return out[0], out[1], out[2]


def _vsop87_xyz_reference(name: str, jd_tt: float) -> tuple[float, float, float]:
    """
    The pre-V1.8 implementation, reading VSOP87A directly.

    Retained ONLY as a test oracle. A second implementation of a rule is
    usually the thing this project refuses, and the exception is the same
    one tests/test_vargas_golden.py relies on: a longhand transcription
    whose entire purpose is to disagree if the optimised path ever drifts.
    """
    t = (jd_tt - 2451545.0) / 365250.0
    series = VSOP87A[name]
    out = []
    for axis in (0, 1, 2):
        total = 0.0
        for power, terms in series[axis].items():
            block = 0.0
            for amplitude, phase, frequency in terms:
                block += amplitude * math.cos(phase + frequency * t)
            total += block * (t ** power)
        out.append(total)
    return out[0], out[1], out[2]


def keplerian_xyz(body: str, jd_tt: float) -> tuple[float, float, float]:
    """
    Heliocentric rectangular coordinates from the JPL Keplerian element set.

    Retained for the bodies VSOP87 is not carried for, and so that the two
    theories can be compared directly by the accuracy tooling.
    """
    name = _SANSKRIT_TO_ENGLISH.get(body, body)
    if name not in _ELEMENTS:
        raise ValueError(f"No orbital elements for '{body}'")
    base, rate = _ELEMENTS[name]
    t = centuries(jd_tt)
    a, e, inc, mean_lon, peri_lon, node_lon = (b + r * t for b, r in zip(base, rate))

    arg_peri = peri_lon - node_lon
    ecc_anom = _solve_kepler(mean_lon - peri_lon, e)

    # Position in the orbital plane.
    x_orb = a * (_cos(ecc_anom) - e)
    y_orb = a * math.sqrt(max(0.0, 1 - e * e)) * _sin(ecc_anom)

    cw, sw = _cos(arg_peri), _sin(arg_peri)
    cn, sn = _cos(node_lon), _sin(node_lon)
    ci, si = _cos(inc), _sin(inc)

    x = (cw * cn - sw * sn * ci) * x_orb + (-sw * cn - cw * sn * ci) * y_orb
    y = (cw * sn + sw * cn * ci) * x_orb + (-sw * sn + cw * cn * ci) * y_orb
    z = (sw * si) * x_orb + (cw * si) * y_orb
    return x, y, z


# Which theory is used for which body. VSOP87 is carried for Earth, Jupiter
# and Saturn; the rest still use the Keplerian elements.
#
# EARTH IS IN THIS LIST ON PURPOSE. Geocentric longitude is the direction of
# the vector from the Earth to the planet, so an error in the Earth's
# heliocentric position projects straight onto every planet's apparent place.
# Measured: using VSOP87 for Jupiter and Saturn but leaving Earth on the
# Keplerian elements gives a worst case of 7.1" for Jupiter, against 2.9" when
# Earth is upgraded too — 1.7x worse. Upgrading Earth also improved Mercury
# (3.2x), Venus (2.4x) and Mars (1.16x) at no extra cost, since they all read
# the same Earth vector.
VSOP87_BODIES = frozenset(VSOP87A)

THEORY_FOR_BODY = {
    "Mercury": "JPL Keplerian elements (1800-2050)",
    "Venus": "JPL Keplerian elements (1800-2050)",
    "Earth": "VSOP87A",
    "Mars": "VSOP87A",
    "Jupiter": "VSOP87A",
    "Saturn": "VSOP87A",
}


def heliocentric_xyz(body: str, jd_tt: float) -> tuple[float, float, float]:
    """
    Heliocentric rectangular coordinates on the J2000 ecliptic, in au.

    Dispatches to VSOP87 where this build carries the series for that body,
    and to the Keplerian elements otherwise. Both return the same frame, so
    every downstream stage — light-time, aberration, precession, nutation,
    ayanamsha, speed, retrogression — is unchanged.
    """
    name = _SANSKRIT_TO_ENGLISH.get(body, body)
    if name in VSOP87_BODIES:
        return vsop87_xyz(name, jd_tt)
    return keplerian_xyz(name, jd_tt)


def theory_used(body: str) -> str:
    """Name of the theory behind a body's position, for provenance reporting."""
    name = _SANSKRIT_TO_ENGLISH.get(body, body)
    if body in ("Surya", "Sun"):
        return "Meeus ch.25 solar theory"
    if body in ("Chandra", "Moon"):
        return "Meeus ch.47 truncated ELP2000"
    if body in ("Rahu", "Ketu", "North Node", "South Node"):
        return "osculating node of the Meeus ch.47 lunar orbit"
    return THEORY_FOR_BODY.get(name, "unknown")


def planet_apparent_longitude(body: str, jd_tt: float) -> float:
    """
    Apparent geocentric tropical longitude of date for a planet, in degrees.
    Includes light-time and annual aberration.
    """
    ex, ey, ez = heliocentric_xyz("Earth", jd_tt)
    px, py, pz = heliocentric_xyz(body, jd_tt)

    # Light-time: see the planet where it was when the light left it.
    for _ in range(3):
        dx, dy, dz = px - ex, py - ey, pz - ez
        distance = math.sqrt(dx * dx + dy * dy + dz * dz)
        px, py, pz = heliocentric_xyz(body, jd_tt - distance * _LIGHT_TIME_PER_AU)

    dx, dy, dz = px - ex, py - ey, pz - ez
    lon_j2000 = _deg(math.degrees(math.atan2(dy, dx)))
    lat_j2000 = math.degrees(math.atan2(dz, math.sqrt(dx * dx + dy * dy)))

    lon = _deg(lon_j2000 + precession_in_longitude(jd_tt))

    # Annual aberration (main term) and nutation in longitude.
    sun_lon = sun_true_longitude(jd_tt)
    lon += -_ABERRATION_CONST * _cos(sun_lon - lon) / _cos(lat_j2000)
    d_psi, _ = nutation(jd_tt)
    return _deg(lon + d_psi)


def planet_latitude(body: str, jd_tt: float) -> float:
    """Apparent geocentric ecliptic latitude, in degrees."""
    ex, ey, ez = heliocentric_xyz("Earth", jd_tt)
    px, py, pz = heliocentric_xyz(body, jd_tt)
    for _ in range(3):
        dx, dy, dz = px - ex, py - ey, pz - ez
        distance = math.sqrt(dx * dx + dy * dy + dz * dz)
        px, py, pz = heliocentric_xyz(body, jd_tt - distance * _LIGHT_TIME_PER_AU)
    dx, dy, dz = px - ex, py - ey, pz - ez
    return math.degrees(math.atan2(dz, math.sqrt(dx * dx + dy * dy)))


def geocentric_distance(body: str, jd_tt: float) -> float:
    """Geocentric distance in au."""
    ex, ey, ez = heliocentric_xyz("Earth", jd_tt)
    px, py, pz = heliocentric_xyz(body, jd_tt)
    dx, dy, dz = px - ex, py - ey, pz - ez
    return math.sqrt(dx * dx + dy * dy + dz * dz)


# ── Unified body access ───────────────────────────────────────────────────────

def tropical_longitude(body: str, jd_tt: float, true_node: bool = True) -> float:
    """Apparent tropical longitude of date for any supported body."""
    if body in ("Surya", "Sun"):
        return sun_apparent_longitude(jd_tt)
    if body in ("Chandra", "Moon"):
        return moon_apparent_longitude(jd_tt)
    if body in ("Rahu", "North Node"):
        return lunar_node(jd_tt, true_node)
    if body in ("Ketu", "South Node"):
        return _deg(lunar_node(jd_tt, true_node) + 180.0)
    return planet_apparent_longitude(body, jd_tt)


def daily_motion(body: str, jd_tt: float, true_node: bool = True,
                 step_days: float | None = None) -> float:
    """
    Apparent motion in degrees per day, by central difference.
    Negative means retrograde, which is what dignity and yoga rules need.
    """
    if step_days is None:
        # Slow movers need a wider baseline so element noise does not dominate.
        step_days = 1.0 if body in ("Guru", "Shani", "Jupiter", "Saturn") else 0.5
    before = tropical_longitude(body, jd_tt - step_days, true_node)
    after = tropical_longitude(body, jd_tt + step_days, true_node)
    delta = (after - before) % 360.0
    if delta > 180.0:
        delta -= 360.0
    return delta / (2 * step_days)


# ── Ascendant, Midheaven ──────────────────────────────────────────────────────

def mean_sidereal_time(jd_ut: float) -> float:
    """Greenwich mean sidereal time in degrees."""
    t = (jd_ut - 2451545.0) / 36525.0
    return _deg(280.46061837 + 360.98564736629 * (jd_ut - 2451545.0)
                + 0.000387933 * t * t - t**3 / 38710000.0)


def apparent_sidereal_time(jd_ut: float, jd_tt: float) -> float:
    """Greenwich apparent sidereal time in degrees (includes the equation of equinoxes)."""
    d_psi, d_eps = nutation(jd_tt)
    eps = mean_obliquity(jd_tt) + d_eps
    return _deg(mean_sidereal_time(jd_ut) + d_psi * _cos(eps))


def ascendant(jd_ut: float, jd_tt: float, latitude: float,
              longitude_east: float) -> float:
    """Apparent tropical longitude of the Ascendant (Lagna), in degrees."""
    ramc = _deg(apparent_sidereal_time(jd_ut, jd_tt) + longitude_east)
    d_psi, d_eps = nutation(jd_tt)
    eps = mean_obliquity(jd_tt) + d_eps
    asc = math.degrees(math.atan2(
        _cos(ramc),
        -(_sin(ramc) * _cos(eps) + math.tan(math.radians(latitude)) * _sin(eps))))
    return _deg(asc)


def midheaven(jd_ut: float, jd_tt: float, longitude_east: float) -> float:
    """Apparent tropical longitude of the Midheaven (Dasama Bhava), in degrees."""
    ramc = _deg(apparent_sidereal_time(jd_ut, jd_tt) + longitude_east)
    d_psi, d_eps = nutation(jd_tt)
    eps = mean_obliquity(jd_tt) + d_eps
    return _deg(math.degrees(math.atan2(_sin(ramc), _cos(ramc) * _cos(eps))))


# ── Self-test ─────────────────────────────────────────────────────────────

# (label, computed value, reference value, tolerance in degrees)
# References: Meeus, "Astronomical Algorithms" 2nd ed., examples 25.b, 47.a, 33.a.
def _max_node_libration() -> float:
    """Largest true-node minus mean-node separation over one nodal cycle."""
    worst = 0.0
    jd = 2451545.0
    while jd < 2451545.0 + 6800.0:          # 18.6 years
        gap = abs((true_lunar_node(jd) - mean_lunar_node(jd) + 180.0) % 360.0 - 180.0)
        worst = max(worst, gap)
        jd += 7.0
    return worst


def selftest() -> list[tuple[str, float, float, float, bool]]:
    """Check the ephemeris against published worked examples."""
    checks = [
        ("Sun apparent λ 1992-10-13.0 TT",
         sun_apparent_longitude(2448908.5), 199.90895, 0.001),
        ("Moon apparent λ 1992-04-12.0 TT",
         moon_apparent_longitude(2448724.5), 133.16726, 0.01),
        ("Moon β 1992-04-12.0 TT",
         moon_latitude(2448724.5), -3.229126, 0.0005),
        # Structural check on the geometric node: the true node librates about
        # the mean node over a full 18.6-year nodal cycle with a peak amplitude
        # of 1.889°. Reproducing that amplitude shows the osculating-plane
        # construction has the right physics, independently of any one epoch.
        ("True node libration amplitude (18.6 y)",
         _max_node_libration(), 1.889, 0.05),
        ("Venus apparent λ 1992-12-20.0 TT",
         planet_apparent_longitude("Venus", 2448976.5), 313.08102, 0.02),
        ("Venus apparent β 1992-12-20.0 TT",
         planet_latitude("Venus", 2448976.5), -2.08474, 0.02),
        ("Mean obliquity 1987-04-10.0 TT",
         mean_obliquity(2446895.5), 23.44094629, 0.00001),
        ("Lahiri ayanamsha at J2000.0",
         ayanamsha(2451545.0), 23.85709233, 0.0001),
        ("ΔT in 1988", delta_t_seconds(2447404.0) / 3600.0, 56.14 / 3600.0, 1 / 3600.0),
    ]
    return [(label, value, expected, tol, abs(value - expected) <= tol)
            for label, value, expected, tol in checks]
