def moon_apparent_longitude(jd_tt: float) -> float:
    """Apparent geocentric tropical longitude of the Moon, in degrees."""
    t, lp, d, m, mp, f = _moon_arguments(jd_tt)
    a1 = _deg(119.75 + 131.849 * t)
    a2 = _deg(53.09 + 479264.290 * t)
    ecc = 1 - 0.002516 * t - 0.0000074 * t * t   # eccentricity correction for M

    total = 0.0
    for cd, cm, cmp_, cf, coeff in _MOON_TERMS:
        arg = cd * d + cm * m + cmp_ * mp + cf * f
        term = coeff * _sin(arg)
        if abs(cm) == 1:
            term *= ecc
        elif abs(cm) == 2:
            term *= ecc * ecc
        total += term

    total += 3958 * _sin(a1) + 1962 * _sin(lp - f) + 318 * _sin(a2)
    lon = _deg(lp + total / 1_000_000.0)
    d_psi, _ = nutation(jd_tt)
    return _deg(lon + d_psi)


