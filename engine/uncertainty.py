"""
Numerical uncertainty and boundary safety (V1.2 Part 2)
--------------------------------------------------------
A longitude is never exact. When a graha lies closer to a classification
boundary than the engine's own error envelope for that body, the resulting
rashi, nakshatra, pada or varga sign is NOT determined by the calculation —
it is a coin toss inside the error bar.

This module makes that explicit rather than leaving the caller to remember
which bodies are trustworthy. Every position can be asked whether its
classification is safe, and the answer carries the envelope that produced it.

The envelopes below are MEASURED, not assumed. They come from
tools/measure_accuracy.py, which compares this engine against the Swiss
Ephemeris at 1000 dates across 1800-2050, and are stored in
tests/fixtures/accuracy_profile.json. A test asserts that the constants here
still match that file, so an accuracy change cannot silently leave stale
tolerances behind.

Layer: SOFTWARE HEURISTIC over an ASTRONOMICAL FACT. The envelope is a
measured astronomical quantity; the decision to warn at the p99.9 level
rather than at the median is an engineering choice, and is stated as one.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Optional

# Worst-case measured longitude error, in arcminutes, per body.
#
# The value used is the MAXIMUM observed over 1800-2050, not the median or the
# 95th percentile. A boundary warning exists to stop a caller trusting a
# classification that could be wrong, so the conservative end of the
# distribution is the honest one to use.
#
# Source: tests/fixtures/accuracy_profile.json, regenerated by
# tools/measure_accuracy.py. Figures below are V1.3 (Earth, Mars, Jupiter and
# Saturn on VSOP87A).
#
# These are AGREEMENT WITH A REFERENCE, not absolute accuracy. The reference
# (Swiss Ephemeris, Moshier mode) has its own uncertainty of order an
# arcsecond for the outer bodies, so an envelope of a few arcseconds means
# "indistinguishable from the reference", not "correct to a few arcseconds".
ACCURACY_ARCMIN: dict[str, float] = {
    "Surya": 0.57,
    "Chandra": 0.17,
    "Mangal": 0.14,      # VSOP87A as of V1.3 (was 3.20 on Keplerian elements)
    "Budha": 0.21,
    "Guru": 0.05,        # VSOP87A
    "Shukra": 0.64,
    "Shani": 0.07,       # VSOP87A
    "Rahu": 1.11,        # osculating true node — the limiting body since V1.3
    "Ketu": 1.11,
}

# The Ascendant is computed to 4.5" worst case, but its real uncertainty is
# dominated by the birth time and the birth place, not by the arithmetic.
# Four seconds of clock error moves it by about one arcminute.
LAGNA_ARCMIN = 0.075

# Mean node, when selected, is more accurate than the true node.
MEAN_NODE_ARCMIN = 0.30

# Multiplier applied to the measured envelope when deciding whether to warn.
# 1.0 means "warn when the body is nearer the boundary than its own worst
# measured error". Raising it widens the warning band.
SAFETY_FACTOR = 1.0

RASHI_SPAN = 30.0
NAKSHATRA_SPAN = 360.0 / 27.0          # 13°20'
PADA_SPAN = NAKSHATRA_SPAN / 4.0       # 3°20'


@dataclass(frozen=True)
class BoundaryProximity:
    """How close a longitude sits to one kind of classification boundary."""

    boundary_type: str           # "rashi" | "nakshatra" | "pada" | varga key
    distance_arcmin: float       # to the nearer edge of the current division
    envelope_arcmin: float       # the body's measured error envelope
    at_risk: bool                # distance < envelope * SAFETY_FACTOR
    boundary_longitude: float    # the nearer edge, in absolute degrees
    direction: str               # "below" if the edge is behind, else "above"

    def describe(self) -> str:
        verdict = "UNRESOLVED" if self.at_risk else "safe"
        return (f"{self.boundary_type}: {self.distance_arcmin:.2f}' from the "
                f"boundary, envelope {self.envelope_arcmin:.2f}' — {verdict}")


@dataclass
class PositionUncertainty:
    """The uncertainty verdict for one body's position."""

    body: str
    longitude: float
    accuracy_arcmin: float
    theory: str = ""
    proximities: list[BoundaryProximity] = field(default_factory=list)

    @property
    def boundary_warning(self) -> bool:
        return any(p.at_risk for p in self.proximities)

    @property
    def boundary_types(self) -> list[str]:
        return [p.boundary_type for p in self.proximities if p.at_risk]

    @property
    def boundary_type(self) -> Optional[str]:
        """The finest boundary at risk, which is the one that matters most."""
        order = {"rashi": 0, "nakshatra": 1, "pada": 2}
        at_risk = [p for p in self.proximities if p.at_risk]
        if not at_risk:
            return None
        at_risk.sort(key=lambda p: order.get(p.boundary_type, 3))
        return at_risk[0].boundary_type

    def to_dict(self) -> dict:
        """The shape specified in the V1.2 brief, plus the supporting detail."""
        return {
            "planet": self.body,
            "longitude": round(self.longitude, 6),
            "accuracy_arcmin": self.accuracy_arcmin,
            "boundary_warning": self.boundary_warning,
            "boundary_type": self.boundary_type,
            "theory": self.theory,
            "proximities": [
                {
                    "boundary_type": p.boundary_type,
                    "distance_arcmin": round(p.distance_arcmin, 4),
                    "envelope_arcmin": p.envelope_arcmin,
                    "at_risk": p.at_risk,
                    "boundary_longitude": round(p.boundary_longitude, 6),
                    "direction": p.direction,
                }
                for p in self.proximities
            ],
        }


def envelope_for(body: str, true_node: bool = True) -> float:
    """Measured worst-case error envelope for a body, in arcminutes."""
    if body in ("Rahu", "Ketu") and not true_node:
        return MEAN_NODE_ARCMIN
    if body == "Lagna":
        return LAGNA_ARCMIN
    return ACCURACY_ARCMIN.get(body, max(ACCURACY_ARCMIN.values()))


def _proximity(longitude: float, span: float, label: str,
               envelope_arcmin: float) -> BoundaryProximity:
    """Distance to the nearer edge of the division of the given span."""
    position_in_division = longitude % span
    to_lower = position_in_division
    to_upper = span - position_in_division
    if to_lower <= to_upper:
        distance, direction = to_lower, "below"
        edge = longitude - to_lower
    else:
        distance, direction = to_upper, "above"
        edge = longitude + to_upper
    distance_arcmin = distance * 60.0
    return BoundaryProximity(
        boundary_type=label,
        distance_arcmin=distance_arcmin,
        envelope_arcmin=envelope_arcmin,
        at_risk=distance_arcmin < envelope_arcmin * SAFETY_FACTOR,
        boundary_longitude=edge % 360.0,
        direction=direction,
    )


def assess_position(body: str, longitude: float, true_node: bool = True,
                    theory: str = "",
                    varga_spans: Optional[dict[str, float]] = None
                    ) -> PositionUncertainty:
    """
    Whether this body's classification is resolved by the calculation.

    `varga_spans` maps a varga key to the arc of one of its divisions, e.g.
    {"D9": 30/9}. Vargas magnify uncertainty: a D60 division is half a degree
    wide, so a body that is comfortably placed in its rashi can still be
    unresolved in D60.
    """
    envelope = envelope_for(body, true_node)
    proximities = [
        _proximity(longitude, RASHI_SPAN, "rashi", envelope),
        _proximity(longitude, NAKSHATRA_SPAN, "nakshatra", envelope),
        _proximity(longitude, PADA_SPAN, "pada", envelope),
    ]
    for key, span in (varga_spans or {}).items():
        proximities.append(_proximity(longitude, span, key, envelope))

    return PositionUncertainty(
        body=body, longitude=longitude % 360.0,
        accuracy_arcmin=envelope, theory=theory, proximities=proximities,
    )


def varga_division_spans(varga_divisions: dict[str, int]) -> dict[str, float]:
    """
    Arc of one division for each varga, in degrees.

    D30 is excluded: its parts are unequal (5/5/8/7/5 degrees), so a single
    span does not describe it and a proximity computed from one would be
    wrong. Reporting nothing is better than reporting a number that is not
    true of the chart.
    """
    return {key: RASHI_SPAN / divisions
            for key, divisions in varga_divisions.items()
            if divisions > 1 and key != "D30"}


def summarise(uncertainties: dict[str, PositionUncertainty]) -> dict:
    """Chart-level view: which bodies are unresolved, and against what."""
    at_risk = {body: u.boundary_types
               for body, u in uncertainties.items() if u.boundary_warning}
    return {
        "safety_factor": SAFETY_FACTOR,
        "basis": ("maximum measured error against the Swiss Ephemeris over "
                  "1800-2050; see tests/fixtures/accuracy_profile.json"),
        "bodies_with_warnings": sorted(at_risk),
        "warnings": at_risk,
        "envelopes_arcmin": {body: u.accuracy_arcmin
                             for body, u in uncertainties.items()},
    }
